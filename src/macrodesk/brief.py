"""`macrodesk brief`: a fixed playbook run through the Stage 2 graph, written to
outputs/brief-<date>.md. Deterministic questions make the output comparable
day to day and make the command schedulable (cron / launchd / LangSmith)."""

from __future__ import annotations

import sqlite3
from datetime import date
from pathlib import Path
from typing import Callable

from langchain_core.messages import AIMessage

from macrodesk.config import PROJECT_ROOT, get_settings

PLAYBOOK = [
    ("Labor market", "Summarise the latest JOLTS report (openings, hires, quits, layoffs) and the unemployment "
                     "rate with 12-month changes, and plot openings and quits since 2019."),
    ("Rates and yield curve", "Give a yield-curve snapshot with 10y-2y and 10y-3m spreads, the fed funds rate, and "
                              "whether the curve has inverted in the last year."),
    ("Growth and inflation", "Report the latest real GDP growth (annualised) and core PCE and core CPI year-over-year "
                             "inflation, with the last 4 readings of each."),
]


def run_brief(graph, thread_id: str, run_turn: Callable[..., None]) -> Path:
    out_dir = PROJECT_ROOT / "outputs"
    out_dir.mkdir(exist_ok=True)
    sections = [f"# Economic brief - {date.today().isoformat()}\n",
                "_Generated by macrodesk (Stage 2 graph, auto-approved plans, critic-checked)._\n"]
    for title, question in PLAYBOOK:
        tid = f"{thread_id}-{title.lower().split()[0]}"
        run_turn(graph, tid, question)
        state = graph.get_state({"configurable": {"thread_id": tid}}).values
        answer = next((m.text for m in reversed(state.get("messages", [])) if isinstance(m, AIMessage)), "(no answer)")
        charts = [line.split("Chart saved to ", 1)[1].strip()
                  for e in state.get("evidence", []) for line in e["result"].splitlines()
                  if line.startswith("Chart saved to ")]
        sections.append(f"\n## {title}\n\n{answer}\n")
        for c in charts:
            sections.append(f"\n![{title}]({Path(c).name})\n")
    path = out_dir / f"brief-{date.today().isoformat()}.md"
    path.write_text("\n".join(sections), encoding="utf-8")
    return path
